# Импортируем модуль сокетов для низкоуровневой сетевой передачи данных
import socket
# Импортируем системный модуль sys для работы с параметрами среды
import sys

# Задаем целевой IP-адрес сервера (локальный петлевой интерфейс 127.0.0.1)
SERVER_HOST = '127.0.0.1'
# Задаем целевой порт сервера в соответствии с заданием работы (60000)
SERVER_PORT = 60000
# Задаем максимальный размер буфера для приема ответной датаграммы (1024 байта)
BUFFER_SIZE = 1024

# Создаем клиентский сетевой сокет семейства IPv4 (AF_INET) с протоколом UDP (SOCK_DGRAM)
client_socket = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)

# Формируем тестовое текстовое сообщение для отправки на UDP-сервер
message = "Тестирование передачи данных без установления соединения по протоколу UDP."
# Кодируем сформированную строку в байтовый массив кодировки UTF-8
data = message.encode('utf-8')

# Выводим в консоль клиента сведения о начале передачи датаграммы
print(f"[*] Отправка UDP-датаграммы на {SERVER_HOST}:{SERVER_PORT}: \"{message}\"")
# Передаем датаграмму на указанный адрес и порт без предварительного установления соединения
client_socket.sendto(data, (SERVER_HOST, SERVER_PORT))

# Получаем и отображаем локальный порт, динамически выделенный клиенту ядром операционной системы
local_ip, local_port = client_socket.getsockname()
# Выводим информацию об исходящем клиентском сокете
print(f"[+] Датаграмма отправлена с локального сокета {local_ip}:{local_port}")

# Ожидаем и принимаем ответную датаграмму от сервера вместе с адресом источника
response_data, server_address = client_socket.recvfrom(BUFFER_SIZE)
# Декодируем принятые ответные байты в читаемую строку UTF-8
response_text = response_data.decode('utf-8')
# Выводим на экран полученный от сервера преобразованный текст (в верхнем регистре)
print(f"[✓] Получен ответ от сервера {server_address[0]}:{server_address[1]}: \"{response_text}\"")

# Закрываем сокет и освобождаем связанные системные дескрипторы
client_socket.close()
# Выводим уведомление об успешном завершении работы клиентской программы
print("[+] Клиентский UDP-сокет закрыт. Работа завершена.")
