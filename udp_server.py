# Импортируем стандартный модуль сетевых сокетов для работы с протоколами стека TCP/IP
import socket
# Импортируем модуль sys для взаимодействия со стандартными системными потоками
import sys

# Определяем IP-адрес для прослушивания (0.0.0.0 — привязка сокета ко всем доступным сетевым интерфейсам)
HOST = '0.0.0.0'
# Определяем константу рабочего UDP-порта сервиса (в соответствии с заданием выбран порт 60000)
PORT = 60000
# Задаем размер буфера для приема одного входящего UDP-пакета (датаграммы) в байтах (1024 байта)
BUFFER_SIZE = 1024

# Создаем сокет с поддержкой адресации IPv4 (AF_INET) и протокола датаграмм UDP (SOCK_DGRAM)
server_socket = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
# Привязываем созданный UDP-сокет к заданному IP-адресу и порту операционной системы
server_socket.bind((HOST, PORT))
# Выводим в консоль информационное сообщение о готовности UDP-сервера к приему датаграмм
print(f"[+] UDP-сервер запущен и ожидает датаграммы на порту {PORT}...")

# Запускаем бесконечный цикл приема и обработки независимых датаграмм от клиентов
while True:
    # Блокирующий вызов recvfrom: ожидаем поступления датаграммы, извлекая данные и кортеж адреса отправителя
    data, client_address = server_socket.recvfrom(BUFFER_SIZE)
    # Выводим в стандартный поток вывода информацию о сетевом адресе (IP:порт) отправителя датаграммы
    print(f"\n[+] Получена датаграмма от клиента: {client_address[0]}:{client_address[1]}")
    # Декодируем байтовый массив полезной нагрузки датаграммы в строку формата UTF-8
    message = data.decode('utf-8')
    # Выводим в консоль сервера исходный текст принятого клиентского сообщения
    print(f"[*] Текст сообщения: \"{message}\"")
    # Преобразуем строковое сообщение в верхний регистр (капс) согласно заданию работы
    upper_message = message.upper()
    # Кодируем преобразованную строку обратно в байтовый формат UTF-8 для отправки по сети
    response_data = upper_message.encode('utf-8')
    # Отправляем ответную датаграмму обратно на точный сетевой адрес клиента с помощью функции sendto
    server_socket.sendto(response_data, client_address)
    # Выводим в консоль подтверждение успешной отправки сформированного UDP-ответа клиенту
    print(f"[✓] Отправлен UDP-ответ клиенту: \"{upper_message}\"")
